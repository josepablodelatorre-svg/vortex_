const { chromium, devices } = require('playwright');
const ok = (c, m) => { console.log((c ? 'PASS ' : 'FAIL ') + m); if (!c) process.exitCode = 1; };
(async () => {
  const b = await chromium.launch();
  const p = await (await b.newContext({ ...devices['iPhone 13'] })).newPage();
  await p.addInitScript(() => localStorage.setItem('vortex-tutorial', '1')); // skip the first-run tutorial
  const errs = []; p.on('pageerror', e => errs.push(e.message));
  const ev = (x) => p.evaluate(x);
  await p.goto('http://127.0.0.1:8765/index.html'); await ev('localStorage.clear()'); await p.reload(); await p.waitForTimeout(800);
  await p.screenshot({ path: process.argv[2] + '/sc-splash.png' });
  await p.touchscreen.tap(195, 600); await p.waitForTimeout(400);
  ok(await ev('titleScreen') === 'menu' && await ev('state') === 'title', 'tap on the splash opens the menu (no run started)');
  await p.screenshot({ path: process.argv[2] + '/sc-menu.png' });
  await p.tap('[data-screen="menu"] [data-go="hangar"]'); await p.waitForTimeout(400);
  ok(await ev('titleScreen') === 'hangar', 'HANGAR opens');
  await p.tap('#shipclass button[data-class="2"]'); await p.waitForTimeout(200);
  await p.screenshot({ path: process.argv[2] + '/sc-hangar.png' });
  await p.tap('[data-screen="hangar"] .back'); await p.waitForTimeout(300);
  ok((await ev(`document.getElementById('loadout').textContent`)).includes('TANK'), 'menu shows the loadout (TANK)');
  await p.tap('[data-go="multi"]'); await p.waitForTimeout(300);
  await p.screenshot({ path: process.argv[2] + '/sc-multi.png' });
  await p.tap('[data-screen="multi"] .back'); await p.waitForTimeout(200);
  await p.tap('[data-go="settings"]'); await p.waitForTimeout(300);
  await p.screenshot({ path: process.argv[2] + '/sc-settings.png' });
  await p.tap('[data-screen="settings"] .back'); await p.waitForTimeout(200);
  await p.tap('#playBtn'); await p.waitForTimeout(300);
  ok(await ev('state') === 'playing' && await ev('hullMax') === 230, 'PLAY starts a run with the chosen ship');
  await ev('damageShip(99999)'); await p.waitForTimeout(500);
  await p.screenshot({ path: process.argv[2] + '/sc-over.png' });
  await p.tap('#gameover .menuBtn'); await p.waitForTimeout(300);
  ok(await ev('state') === 'title' && await ev('titleScreen') === 'menu', 'MENU on the results screen returns to the main menu');
  console.log('errors', JSON.stringify(errs));
  await b.close();
})();
