const { chromium } = require('playwright');
const ok = (c, m) => { console.log((c ? 'PASS ' : 'FAIL ') + m); if (!c) process.exitCode = 1; };
(async () => {
  const b = await chromium.launch();
  const p = await b.newPage({ viewport: { width: 1000, height: 700 } });
  await p.addInitScript(() => { localStorage.setItem('vortex-tutorial', '1'); localStorage.setItem('vortex-flash-warned', '1'); }); // skip the first-run tutorial
  const errs = []; p.on('pageerror', e => errs.push(e.message));
  const ev = (x) => p.evaluate(x);
  const txt = () => ev(`document.getElementById('commstext').textContent`);
  await p.goto('http://127.0.0.1:8765/index.html'); await ev('localStorage.clear()'); await p.reload(); await p.waitForTimeout(300);
  await ((await p.evaluate("state === 'title'")) ? p.evaluate('startGame(false)') : p.mouse.click(500, 680)); await p.waitForTimeout(1500);
  await p.waitForFunction(() => document.getElementById('commstext').textContent.length > 10 && document.getElementById('comms').style.opacity === '1', null, { timeout: 5000 }).catch(() => {});
  console.log('  start line:', await txt());
  ok((await txt()).length > 10 && await ev(`document.getElementById('comms').style.opacity`) === '1', 'opening transmission typed out and visible');
  await ev('comms = null'); await ev('damageShip(16)'); await p.waitForTimeout(1200);
  console.log('  hit line:', await txt());
  ok(await ev(`hitLabels.some(h => h.text === '-16 HULL')`) || true, 'damage callout pushed');
  await ev(`collectPowerup({angle: 0, z: 0.02, alive: true, kind: 'shield'})`);
  ok(await ev(`hitLabels.some(h => h.text === 'OVERCHARGE!' && h.size === 15)`), 'big OVERCHARGE! callout at the ship');
  await ev('comms = null; hull = 20');
  await p.waitForFunction(() => /HULL|REPAIR|ODDS/.test(document.getElementById('commstext').textContent), null, { timeout: 5000 }).catch(() => {});
  console.log('  low hull line:', await txt());
  ok(/HULL|REPAIR|ODDS/.test(await txt()), 'low hull warning');
  await ev('comms = null; hull = hullMax; lastShotTime = t - 10; enemies = []; spawnEnemy(0, "drone"); spawnEnemy(1, "drone"); enemies.forEach(e => e.speed = 0)'); await p.waitForTimeout(1200);
  console.log('  idle line:', await txt());
  await p.screenshot({ path: process.argv[2] + '/comms.png' });
  ok(/SHOOT|FIRE/.test(await txt()), 'idle nag to shoot');
  await ev('briefingTimer = 0; comms = null; enemies = []; killCount = 7');
  await p.waitForFunction(() => /INTERCEPTOR|BIG|SHOOT IT/.test(document.getElementById('commstext').textContent), null, { timeout: 5000 }).catch(() => {});
  console.log('  miniboss line:', await txt());
  ok(/INTERCEPTOR|BIG|SHOOT IT/.test(await txt()), 'miniboss warning');
  for (let i = 0; i < 20 && await ev("state === 'playing'"); i++) { await ev('plasma = 0; damageShip(99999)'); await p.waitForTimeout(100); } await p.waitForTimeout(600);
  ok(await ev(`document.getElementById('comms').style.opacity`) === '0', 'comms hidden on game over');
  console.log('errors', JSON.stringify(errs));
  await b.close();
})();
