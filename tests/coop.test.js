const { chromium } = require('playwright');
const ok = (c, m) => { console.log((c ? 'PASS ' : 'FAIL ') + m); if (!c) process.exitCode = 1; };
(async () => {
  const b = await chromium.launch({ args: ['--autoplay-policy=no-user-gesture-required'] });
  const host = await (await b.newContext({ viewport: { width: 1000, height: 760 } })).newPage();
  await host.addInitScript(() => localStorage.setItem('vortex-tutorial', '1')); // skip the first-run tutorial
  const pad = await (await b.newContext({ viewport: { width: 390, height: 760 }, hasTouch: true, isMobile: true })).newPage();
  await pad.addInitScript(() => localStorage.setItem('vortex-tutorial', '1')); // skip the first-run tutorial
  const errs = [];
  host.on('pageerror', e => errs.push('host: ' + e.message));
  pad.on('pageerror', e => errs.push('pad: ' + e.message));
  const H = (x) => host.evaluate(x), P = (x) => pad.evaluate(x);
  await host.goto('http://127.0.0.1:8765/index.html?peerhost=127.0.0.1:9000'); await H('localStorage.clear()'); await host.reload(); await host.waitForTimeout(300);
  await host.evaluate(sel => document.querySelector(sel).click(), '#coopBtn');
  for (let i = 0; i < 50 && !(await H('netId')); i++) await host.waitForTimeout(100);
  const url = await H('padUrl()');
  console.log('  pad url:', url);
  ok(!!(await H('netId')) && (await H(`document.getElementById('qrbox').innerHTML`)).startsWith('<svg'), 'lobby opens with a QR code');
  await host.screenshot({ path: process.argv[2] + '/lobby.png' });
  await pad.goto(url); await pad.waitForTimeout(300);
  await pad.fill('#name', 'trinity');
  await pad.click('#joinBtn');
  for (let i = 0; i < 80 && (await H('coPlayers.length')) === 0; i++) await host.waitForTimeout(100);
  ok(await H('coPlayers.length') === 1 && await H('coPlayers[0].name') === 'TRINITY', 'phone joins as P2 TRINITY');
  await pad.waitForTimeout(500);
  ok(await P(`getComputedStyle(document.getElementById('join')).display`) === 'none', 'pad switches to the controller');
  ok((await H(`document.getElementById('lobbyplayers').textContent`)).includes('TRINITY'), 'lobby lists the player');
  await host.click('#lobbyClose');
  await ((await host.evaluate("state === 'title'")) ? host.evaluate('startGame(false)') : host.mouse.click(500, 740)); await host.waitForTimeout(200);
  await H('briefingTimer = 0; hull = hullMax');
  // phone: touch and hold up-right
  await pad.touchscreen.tap(330, 250);
  await P(`(() => { const c = document.getElementById('pad'); const mk = (type, x, y) => { const tch = new Touch({ identifier: 1, target: c, clientX: x, clientY: y }); c.dispatchEvent(new TouchEvent(type, { touches: type === 'touchend' ? [] : [tch], changedTouches: [tch], bubbles: true, cancelable: true })); }; mk('touchstart', 330, 250); window.__mk = mk; })()`);
  await pad.waitForTimeout(900);
  const aim = await H('coPlayers[0].aim');
  const owned = await H('bolts.filter(b => b.owner === 0).length + pulses.length');
  console.log('  P2 aim', aim.toFixed(2), 'owned bolts+pulses', owned);
  ok(aim > 0.3 && aim < 1.6, 'phone aim arrives (up-right)');
  ok(await H('bolts.some(b => b.owner === 0)'), 'holding the pad fires P2 bolts');
  await host.screenshot({ path: process.argv[2] + '/coop-host.png' });
  await P(`__mk('touchend', 330, 250)`);
  await H('plasma = 0; damageShip(10)'); await pad.waitForTimeout(600);
  const hullTxt = await P(`document.getElementById('hullfill').style.width`);
  ok(parseFloat(hullTxt) < 100, 'pad shows the team hull (' + hullTxt + ')');
  await pad.screenshot({ path: process.argv[2] + '/coop-pad.png' });
  await pad.click('#zap'); await host.waitForTimeout(400);
  ok(await H('zapperCharges') === 0, 'ZAP on the phone fires the team zapper');
  await pad.close({ runBeforeUnload: true }); for (let i = 0; i < 80 && await H('coPlayers.length'); i++) await host.waitForTimeout(100);
  ok(await H('coPlayers.length') === 0, 'closing the pad removes the gunner');
  console.log('errors', JSON.stringify(errs));
  await b.close();
})();
