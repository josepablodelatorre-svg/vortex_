const { chromium } = require('playwright');
const ok = (c, m) => { console.log((c ? 'PASS ' : 'FAIL ') + m); if (!c) process.exitCode = 1; };
(async () => {
  const b = await chromium.launch();
  const p = await b.newPage({ viewport: { width: 1000, height: 640 } });
  const errs = []; p.on('pageerror', e => errs.push(e.message));
  const ev = (x) => p.evaluate(x);
  await p.goto('http://127.0.0.1:8765/index.html'); await p.waitForTimeout(300);
  await ev('startGame(false)'); await p.waitForTimeout(300);
  ok(await p.isVisible('#pauseBtn'), 'pause button shows in a run');
  await p.keyboard.press('KeyP'); await p.waitForTimeout(100);
  ok(await ev('paused') && await p.isVisible('#pause'), 'P pauses and shows the overlay');
  const t0 = await ev('t'); await p.waitForTimeout(600);
  ok(await ev('t') === t0, 'game clock stops while paused');
  await p.screenshot({ path: process.argv[2] + '/pause.png' });
  await p.click('#resumeBtn'); await p.waitForTimeout(300);
  ok(!(await ev('paused')) && await ev('t') > t0, 'RESUME continues');
  await ev(`Object.defineProperty(document, 'hidden', { configurable: true, get: () => true }); document.dispatchEvent(new Event('visibilitychange'))`);
  ok(await ev('paused'), 'hiding the app auto-pauses');
  await p.keyboard.press('Escape'); await p.waitForTimeout(100);
  ok(!(await ev('paused')), 'Esc resumes');
  await p.click('#pauseBtn'); await p.waitForTimeout(100);
  await p.click('#pauseMenuBtn'); await p.waitForTimeout(300);
  ok(await ev('state') === 'title' && !(await ev('paused')) && !(await p.isVisible('#pauseBtn')), 'MENU leaves the run');
  await ev('versus = true; state = "playing"'); await ev('pauseGame()');
  ok(!(await ev('paused')), 'no pause in versus');
  await ev('versus = false; state = "title"');
  console.log('errors', JSON.stringify(errs));
  await b.close();
})();
